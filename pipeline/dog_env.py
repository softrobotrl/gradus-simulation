"""Batched MuJoCo environment for the Gradus dog, with nominal-controller + residual RL.

The dog model is generated by :mod:`pipeline.dog_model` (floating trunk, four
planar two-link legs, eight position-controlled tendon drums).  This module
wraps it in a trainable task:

* **Nominal controller**: a constant stand command, optionally augmented by a
  joint-space PD term mapped through the tendon Jacobian.  This is the
  ``a_nom`` in ``a = a_nom + residual_scale * a_policy``.
* **Action residual**: the policy outputs eight values in ``[-1, 1]``, one per
  tendon.  They are added to the nominal drum angles, clipped, low-pass
  filtered and rate-limited exactly like a servo command.
* **State residual**: the observation starts with the error between the
  measured state and the nominal stand state (height, gravity direction, joint
  positions, joint velocities, body velocity, tendon lengths).  Raw state,
  the nominal action and the applied residual follow.

Two command modes:

* ``"stand"`` - hold the nominal stand pose; the command is zero.
* ``"velocity"`` - track a sampled body-frame forward/lateral/yaw command.
  The nominal controller is still a stand controller, so the residual policy
  has to discover a gait.

Usage::

    from pipeline.dog_env import DogEnv, DogEnvConfig, make_dog_env
    env = make_dog_env(64, command_mode="stand")
    obs = env.reset()["policy"]                       # (64, 82)
    obs, reward, done, extras = env.step(actions)     # actions in [-1, 1]^8
    # extras["time_outs"], extras["final_observation"], extras["log"]

The physics backend is C MuJoCo on CPU threads.  The model itself uses only
features supported by MJX; an MJX backend can be added without changing the
XML or the task definition.
"""

from __future__ import annotations

import math
import os
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, replace
from pathlib import Path

import mujoco
import numpy as np

from pipeline.dog_model import DEFAULT_OUT, LEGS, DogModelConfig, build_dog_xml

LEG_NAMES = tuple(leg.name for leg in LEGS)
HINGE_NAMES = tuple(f"{leg.name}_{joint}" for leg in LEGS for joint in ("hip", "knee"))
TENDON_NAMES = tuple(f"{leg.name}_t{k}" for leg in LEGS for k in (0, 1))
ACTUATOR_NAMES = tuple(f"{name}_servo" for name in TENDON_NAMES)
FOOT_GEOMS = tuple(f"{leg.name}_foot" for leg in LEGS)

# Observation layout, in order: the state residual, then the raw state, then the
# action context.  Shared by the C and the MJX backends, so a policy trained on
# one runs on the other.
OBS_PARTS = (
    ("state_residual", (
        ("base_height_residual", 1),
        ("projected_gravity_residual", 3),
        ("joint_pos_residual", 8),
        ("joint_vel_residual", 8),
        ("velocity_residual", 3),
        ("tendon_length_residual", 8),
    )),
    ("raw_state", (
        ("base_quat", 4),
        ("base_lin_vel", 3),
        ("base_ang_vel", 3),
        ("tendon_tension", 8),
        ("foot_contact", 4),
    )),
    ("action_context", (
        ("nominal_action", 8),
        ("applied_residual", 8),
        ("previous_action", 8),
        ("gait_phase", 2),
        ("command", 3),
    )),
)


def obs_layout() -> dict[str, slice]:
    """Name -> slice of the observation vector, for every part and every group."""
    layout: dict[str, slice] = {}
    start = 0
    for group, parts in OBS_PARTS:
        group_start = start
        for name, size in parts:
            layout[name] = slice(start, start + size)
            start += size
        layout[group] = slice(group_start, start)
    return layout


# MuJoCo records solver divergence in these warning counters; a diverged env is
# turned into NaN so the task layer can terminate and reset it.
_DIVERGED = (mujoco.mjtWarning.mjWARN_BADQACC, mujoco.mjtWarning.mjWARN_BADQPOS, mujoco.mjtWarning.mjWARN_BADQVEL)


@dataclass(frozen=True)
class DogEnvConfig:
    """Task, controller and reward settings.  All angles are radians, lengths metres."""

    # Model
    model_path: str | None = None
    rebuild: bool = False
    num_threads: int | None = None

    # Episode / physics
    episode_s: float = 8.0
    control_dt: float = 0.02

    # Command
    command_mode: str = "stand"           # "stand" or "velocity"
    vx_range: tuple[float, float] = (0.0, 0.4)
    vy_range: tuple[float, float] = (0.0, 0.0)
    wz_range: tuple[float, float] = (0.0, 0.0)

    # Nominal controller: theta_nom = stand_angle + gait + J^-1 * joint PD
    nominal_mode: str = "pd"              # "none", "constant" or "pd"
    stand_angle: float = 0.10             # rad at every drum
    gait_hz: float = 0.0                  # 0 = no open-loop gait
    gait_amp: float = 0.0                 # rad of sinusoidal drum motion
    kp_q: float = 0.30                    # joint-space proportional gain
    kd_q: float = 0.01                    # joint-space damping gain
    residual_scale: float = 0.250          # rad of drum angle per unit policy action
    action_filter: float = 0.50           # first-order servo response per control step
    max_speed: float = 8.0                # rad/s at the drum, rate limit (must match the model)

    # Reward
    alive_reward: float = 1.0
    height_reward: float = 1.0
    upright_reward: float = 0.5
    velocity_reward: float = 0.5
    yaw_reward: float = 0.2
    posture_reward: float = 0.5
    tension_cost: float = 0.001
    rate_cost: float = 0.01
    residual_cost: float = 0.05
    height_target: float = 0.215
    height_sigma: float = 0.020
    upright_sigma: float = 0.15
    velocity_sigma: float = 0.20
    yaw_sigma: float = 0.50
    posture_sigma: float = 0.35

    # Failure / reset
    terminate_height: float = 0.12
    terminate_tilt: float = 0.70          # |projected gravity xy|
    init_height_noise: float = 0.003
    init_tilt_noise: float = 0.02
    init_joint_noise: float = 0.05
    init_vel_noise: float = 0.02
    init_yaw_noise: float = 0.0

    def __post_init__(self) -> None:
        if self.command_mode not in ("stand", "velocity"):
            raise ValueError("command_mode must be 'stand' or 'velocity'")
        if self.nominal_mode not in ("none", "constant", "pd"):
            raise ValueError("nominal_mode must be 'none', 'constant' or 'pd'")
        if self.control_dt <= 0:
            raise ValueError("control_dt must be positive")


@dataclass
class _Buffers:
    """Preallocated per-env arrays filled by the physics threads."""

    qpos: np.ndarray
    qvel: np.ndarray
    actuator_force: np.ndarray
    ten_length: np.ndarray
    ten_velocity: np.ndarray
    xmat: np.ndarray
    foot_pos: np.ndarray
    foot_contact: np.ndarray


class DogEnv:
    """Batched, auto-resetting MuJoCo dog environment with a PyTorch/TensorDict interface."""

    def __init__(self, num_envs: int, config: DogEnvConfig | None = None, seed: int = 0,
                 num_threads: int | None = None, **kwargs):
        if config is None:
            config = DogEnvConfig(**kwargs)
        elif kwargs:
            raise ValueError("pass either config=... or keyword fields, not both")
        if num_threads is not None:
            config = replace(config, num_threads=num_threads)
        if num_envs < 1:
            raise ValueError("num_envs must be at least 1")
        self.cfg = config
        self.num_envs = int(num_envs)
        self.rng = np.random.default_rng(seed)

        model_path = Path(config.model_path) if config.model_path else DEFAULT_OUT / "robot.xml"
        if config.rebuild or not model_path.exists():
            build_dog_xml(model_path.parent, DogModelConfig())
        self.mj_model = mujoco.MjModel.from_xml_path(str(model_path))
        m = self.mj_model

        self.n_substeps = round(config.control_dt / m.opt.timestep)
        if self.n_substeps < 1 or abs(self.n_substeps * m.opt.timestep - config.control_dt) > 1e-9:
            raise ValueError(f"control_dt {config.control_dt} is not a multiple of model timestep {m.opt.timestep}")
        self.dt = config.control_dt
        self.max_steps = max(1, round(config.episode_s / config.control_dt))
        self.max_episode_length = self.max_steps

        # Names are ordered to match the model: legs FL, FR, RL, RR; each leg hip, knee;
        # each leg t0, t1.  Querying by name keeps the env independent of XML ordering.
        self.hinge_qpos = np.array([m.jnt_qposadr[m.joint(n).id] for n in HINGE_NAMES], dtype=np.int64)
        self.hinge_dof = np.array([m.jnt_dofadr[m.joint(n).id] for n in HINGE_NAMES], dtype=np.int64)
        self.cable_qpos = np.array([m.jnt_qposadr[m.joint(m.actuator_trnid[a, 0]).id] for a in range(m.nu)],
                                   dtype=np.int64)
        self.cable_dof = np.array([m.jnt_dofadr[m.joint(m.actuator_trnid[a, 0]).id] for a in range(m.nu)],
                                  dtype=np.int64)
        self.ten_ids = np.array([m.tendon(n).id for n in TENDON_NAMES], dtype=np.int64)
        self.foot_geoms = np.array([m.geom(n).id for n in FOOT_GEOMS], dtype=np.int64)
        self.trunk_body = m.body("trunk").id
        self.root_joint = m.joint("root").id
        self.root_qpos = int(m.jnt_qposadr[self.root_joint])
        self.root_dof = int(m.jnt_dofadr[self.root_joint])
        if self.root_qpos != 0 or self.root_dof != 0:
            raise RuntimeError("expected the free root joint to be first in qpos and qvel")

        self.num_actions = m.nu
        self.ctrl_low = m.actuator_ctrlrange[:, 0].copy()
        self.ctrl_high = m.actuator_ctrlrange[:, 1].copy()
        self.max_step = config.max_speed * config.control_dt
        self.tendon_rest = m.tendon_range[:, 1].copy()
        self.q0 = np.zeros(len(HINGE_NAMES), dtype=np.float64)
        # The drum geometry and the tension limit come from the model, not from a
        # copy in the config: the actuator gear is 1/drum_radius and the actuator
        # force limit times that gear is the cable tension limit.
        self.drum_radius = float(1.0 / m.actuator_gear[0, 0])
        self.max_tension = float(m.actuator_forcerange[0, 1] * m.actuator_gear[0, 0])

        # Constant tendon Jacobian at the stand pose, per leg: rows = tendons, cols = joints.
        self.Jleg = self._tendon_jacobian()
        for leg in range(4):
            det = float(np.linalg.det(self.Jleg[leg]))
            if abs(det) < 1e-6:
                raise RuntimeError(f"tendon Jacobian for leg {leg} is singular (det={det:.3g}); the two "
                                   "tendons cannot control both joints")

        # Open-loop trot phase offsets: FL and RR together, FR and RL opposite.
        leg_phase = np.array([0.0, math.pi, math.pi, 0.0])  # FL, FR, RL, RR
        tendon_phase = np.array([0.0, math.pi / 2])         # hip tendon, knee tendon
        self.gait_phase = np.repeat(leg_phase, 2) + np.tile(tendon_phase, 4)

        # Observation layout, in order.  The first block is the explicit state residual.
        self._obs_layout: dict[str, slice] = obs_layout()
        self.num_obs = max(s.stop for s in self._obs_layout.values())

        # Per-env task state.
        self.t = np.zeros(self.num_envs, dtype=np.int32)
        self.command = np.zeros((self.num_envs, 3), dtype=np.float32)
        self.phase = np.zeros(self.num_envs, dtype=np.float64)
        self.prev_action = np.zeros((self.num_envs, self.num_actions), dtype=np.float32)
        self.prev_target = np.zeros((self.num_envs, self.num_actions), dtype=np.float32)
        self.nominal_angle = np.zeros((self.num_envs, self.num_actions), dtype=np.float32)
        self.obs = np.zeros((self.num_envs, self.num_obs), dtype=np.float32)

        # Physics data and buffers.
        self.datas = [mujoco.MjData(m) for _ in range(self.num_envs)]
        self._geom_to_foot = {int(g): i for i, g in enumerate(self.foot_geoms)}
        self._buf = _Buffers(
            qpos=np.zeros((self.num_envs, m.nq), np.float32),
            qvel=np.zeros((self.num_envs, m.nv), np.float32),
            actuator_force=np.zeros((self.num_envs, m.nu), np.float32),
            ten_length=np.zeros((self.num_envs, m.ntendon), np.float32),
            ten_velocity=np.zeros((self.num_envs, m.ntendon), np.float32),
            xmat=np.zeros((self.num_envs, 9), np.float32),
            foot_pos=np.zeros((self.num_envs, 4, 3), np.float32),
            foot_contact=np.zeros((self.num_envs, 4), np.float32),
        )
        threads = max(1, min(config.num_threads or os.cpu_count() or 1, self.num_envs))
        self.num_threads = threads
        self._chunks = [range(i, self.num_envs, threads) for i in range(threads)]
        self._pool = ThreadPoolExecutor(threads)

        self._torch = None
        self._TensorDict = None
        self.device = "cpu"
        self.extras: dict = {}
        self.reset()

    # ----- model helpers -----

    def _tendon_jacobian(self) -> np.ndarray:
        """d(tendon length)/d(joint angle) at qpos0, as a (4 legs, 2 tendons, 2 joints) array."""
        m = self.mj_model
        data = mujoco.MjData(m)
        eps = 1e-6
        J = np.zeros((m.ntendon, len(self.hinge_qpos)), dtype=np.float64)
        for j, adr in enumerate(self.hinge_qpos):
            qp = m.qpos0.copy()
            qp[adr] += eps
            data.qpos[:] = qp
            mujoco.mj_forward(m, data)
            lp = data.ten_length.copy()
            qm = m.qpos0.copy()
            qm[adr] -= eps
            data.qpos[:] = qm
            mujoco.mj_forward(m, data)
            lm = data.ten_length.copy()
            J[:, j] = (lp - lm) / (2 * eps)
        # Rows are tendon index (FL_t0, FL_t1, FR_t0, ...); columns are joint index
        # (FL_hip, FL_knee, FR_hip, ...).  The matrix is block diagonal per leg.
        return np.array([J[2 * leg:2 * leg + 2, 2 * leg:2 * leg + 2] for leg in range(4)])

    # ----- physics threads -----

    def _run(self, fn) -> None:
        for future in [self._pool.submit(fn, chunk) for chunk in self._chunks]:
            future.result()

    def _gather(self, i: int, d: mujoco.MjData) -> None:
        b = self._buf
        b.qpos[i] = d.qpos
        if sum(d.warning[w].number for w in _DIVERGED):
            b.qpos[i] = np.nan
        b.qvel[i] = d.qvel
        b.actuator_force[i] = d.actuator_force
        b.ten_length[i] = d.ten_length
        b.ten_velocity[i] = d.ten_velocity
        b.xmat[i] = d.xmat[self.trunk_body]
        b.foot_pos[i] = d.geom_xpos[self.foot_geoms]
        b.foot_contact[i] = 0.0
        for c in range(d.ncon):
            contact = d.contact[c]
            for geom in (contact.geom1, contact.geom2):
                foot = self._geom_to_foot.get(int(geom))
                if foot is not None:
                    b.foot_contact[i, foot] = 1.0

    def _physics_step(self, target: np.ndarray) -> None:
        m, n_sub = self.mj_model, self.n_substeps

        def work(chunk):
            for i in chunk:
                d = self.datas[i]
                d.ctrl[:] = target[i]
                mujoco.mj_step(m, d, nstep=n_sub)
                self._gather(i, d)

        self._run(work)

    def _physics_reset(self, idx: np.ndarray, qpos: np.ndarray, qvel: np.ndarray, ctrl: np.ndarray) -> None:
        m = self.mj_model
        # qpos/qvel/ctrl are compact rows for `idx`; map env index -> row.
        row = {int(env_i): k for k, env_i in enumerate(idx)}

        def work(chunk):
            for i in chunk:
                k = row.get(int(i))
                if k is None:
                    continue
                d = self.datas[i]
                mujoco.mj_resetData(m, d)
                d.qpos[:] = qpos[k]
                d.qvel[:] = qvel[k]
                d.ctrl[:] = ctrl[k]
                mujoco.mj_forward(m, d)
                self._gather(i, d)

        self._run(work)

    # ----- controller and task -----

    def _nominal_angles(self, q: np.ndarray, qd: np.ndarray, phase: np.ndarray) -> np.ndarray:
        """Nominal drum angles (rad) for a batch of states."""
        n = q.shape[0]
        if self.cfg.nominal_mode == "none":
            return np.zeros((n, self.num_actions), dtype=np.float32)
        base = np.full((n, self.num_actions), self.cfg.stand_angle, dtype=np.float64)
        if self.cfg.gait_amp:
            base += self.cfg.gait_amp * np.sin(phase[:, None] + self.gait_phase[None, :])
        if self.cfg.nominal_mode == "pd":
            dq = self.cfg.kp_q * (self.q0[None, :] - q) - self.cfg.kd_q * qd
            d_l = np.einsum("lij,nlj->nli", self.Jleg, dq.reshape(n, 4, 2))
            base += d_l.reshape(n, self.num_actions) / self.drum_radius
        return np.clip(base, self.ctrl_low[None, :], self.ctrl_high[None, :]).astype(np.float32)

    def _state(self, idx: np.ndarray) -> dict[str, np.ndarray]:
        """Gather the quantities the task and observation need."""
        b = self._buf
        qpos, qvel = b.qpos[idx], b.qvel[idx]
        q = qpos[:, self.hinge_qpos].astype(np.float64)
        qd = qvel[:, self.hinge_dof].astype(np.float64)
        R = b.xmat[idx].reshape(-1, 3, 3).astype(np.float64)
        gravity = np.einsum("nij,j->ni", R.transpose(0, 2, 1), np.array([0.0, 0.0, -1.0]))
        v_world = qvel[:, self.root_dof:self.root_dof + 3].astype(np.float64)
        v_body = np.einsum("nij,nj->ni", R.transpose(0, 2, 1), v_world)
        w_body = qvel[:, self.root_dof + 3:self.root_dof + 6].astype(np.float64)
        tension = b.actuator_force[idx].astype(np.float64) / self.drum_radius
        return {
            "qpos": qpos, "qvel": qvel, "q": q, "qd": qd, "R": R,
            "gravity": gravity, "v_body": v_body, "w_body": w_body,
            "ten_length": b.ten_length[idx].astype(np.float64),
            "tension": tension,
            "tension_norm": tension / self.max_tension,
            "foot_contact": b.foot_contact[idx].astype(np.float64),
        }

    def _obs(self, idx: np.ndarray, sim: dict[str, np.ndarray], nominal: np.ndarray) -> np.ndarray:
        cmd = self.command[idx]
        velocity_residual = np.concatenate([sim["v_body"][:, :2] - cmd[:, :2],
                                            sim["w_body"][:, 2:3] - cmd[:, 2:3]], axis=1)
        state_residual = np.concatenate([
            (sim["qpos"][:, 2] - self.cfg.height_target)[:, None],
            sim["gravity"] - np.array([0.0, 0.0, -1.0]),
            sim["q"] - self.q0[None, :],
            sim["qd"],
            velocity_residual,
            sim["ten_length"] - self.tendon_rest[None, :],
        ], axis=1)
        raw_state = np.concatenate([
            sim["qpos"][:, 3:7],
            sim["v_body"],
            sim["w_body"],
            sim["tension_norm"],
            sim["foot_contact"],
        ], axis=1)
        phase = self.phase[idx]
        phase_sc = np.stack([np.sin(phase), np.cos(phase)], axis=1)
        action_context = np.concatenate([
            nominal,
            self.prev_target[idx] - nominal,
            self.prev_action[idx],
            phase_sc,
            cmd,
        ], axis=1)
        return np.concatenate([state_residual, raw_state, action_context], axis=1).astype(np.float32)

    def _reward(self, sim: dict[str, np.ndarray], target: np.ndarray, action: np.ndarray) -> tuple:
        cfg = self.cfg
        idx = np.arange(self.num_envs)
        qpos = sim["qpos"]
        height = np.exp(-np.square((qpos[:, 2] - cfg.height_target) / cfg.height_sigma))
        tilt = np.linalg.norm(sim["gravity"][:, :2], axis=1)
        upright = np.exp(-np.square(tilt / cfg.upright_sigma))
        cmd = self.command
        vel_err = np.square(sim["v_body"][:, 0] - cmd[:, 0]) + np.square(sim["v_body"][:, 1] - cmd[:, 1])
        yaw_err = np.square(sim["w_body"][:, 2] - cmd[:, 2])
        velocity = np.exp(-vel_err / cfg.velocity_sigma**2)
        yaw = np.exp(-yaw_err / cfg.yaw_sigma**2)
        posture = np.exp(-np.mean(np.square(sim["q"]), axis=1) / cfg.posture_sigma**2)
        tension_cost = np.mean(np.square(sim["tension_norm"]), axis=1)
        rate = np.mean(np.square((target - self.prev_target) / self.max_step), axis=1)
        residual = np.mean(np.square(action), axis=1)
        reward = (cfg.alive_reward + cfg.height_reward * height + cfg.upright_reward * upright
                  + cfg.velocity_reward * velocity + cfg.yaw_reward * yaw + cfg.posture_reward * posture
                  - cfg.tension_cost * tension_cost - cfg.rate_cost * rate - cfg.residual_cost * residual)
        reward = np.where(np.isfinite(reward), reward, 0.0)
        failed = ((qpos[:, 2] < cfg.terminate_height) | (tilt > cfg.terminate_tilt)
                  | ~np.isfinite(qpos).all(axis=1))
        speed = np.linalg.norm(sim["v_body"][:, :2], axis=1)
        metrics = {
            "base_height": qpos[:, 2],
            "tilt": tilt,
            "speed": speed,
            "vx": sim["v_body"][:, 0],
            "vy": sim["v_body"][:, 1],
            "wz": sim["w_body"][:, 2],
            "height_reward": height,
            "upright_reward": upright,
            "velocity_reward": velocity,
            "yaw_reward": yaw,
            "posture_reward": posture,
            "tension": np.mean(sim["tension_norm"], axis=1),
            "action_rate": rate,
            "residual": np.mean(np.abs(action), axis=1),
            "foot_contact": np.mean(sim["foot_contact"], axis=1),
        }
        return reward, failed, metrics

    # ----- reset -----

    def _reset_indices(self, idx: np.ndarray) -> None:
        cfg = self.cfg
        idx = np.asarray(idx, dtype=np.int64)
        n = len(idx)
        if n == 0:
            return
        m = self.mj_model
        qpos = np.tile(m.qpos0, (n, 1)).astype(np.float64)
        qvel = np.zeros((n, m.nv), dtype=np.float64)

        qpos[:, 2] += self.rng.uniform(-cfg.init_height_noise, cfg.init_height_noise, n)
        roll = self.rng.uniform(-cfg.init_tilt_noise, cfg.init_tilt_noise, n)
        pitch = self.rng.uniform(-cfg.init_tilt_noise, cfg.init_tilt_noise, n)
        yaw = self.rng.uniform(-cfg.init_yaw_noise, cfg.init_yaw_noise, n) if cfg.init_yaw_noise else np.zeros(n)
        qpos[:, 3:7] = self._euler_to_quat(roll, pitch, yaw)

        joint_noise = self.rng.uniform(-cfg.init_joint_noise, cfg.init_joint_noise, (n, len(HINGE_NAMES)))
        qpos[:, self.hinge_qpos] = self.q0[None, :] + joint_noise
        qvel[:, self.root_dof:self.root_dof + 6] = self.rng.uniform(
            -cfg.init_vel_noise, cfg.init_vel_noise, (n, 6))
        qvel[:, self.hinge_dof] = self.rng.uniform(-cfg.init_vel_noise, cfg.init_vel_noise,
                                                   (n, len(HINGE_NAMES)))

        command = np.zeros((n, 3), dtype=np.float32)
        if cfg.command_mode == "velocity":
            command[:, 0] = self.rng.uniform(*cfg.vx_range, n)
            command[:, 1] = self.rng.uniform(*cfg.vy_range, n)
            command[:, 2] = self.rng.uniform(*cfg.wz_range, n)
        phase = self.rng.uniform(0, 2 * math.pi, n) if cfg.gait_hz else np.zeros(n)

        nominal = self._nominal_angles(qpos[:, self.hinge_qpos], qvel[:, self.hinge_dof], phase)
        qpos[:, self.cable_qpos] = self.drum_radius * nominal

        self.t[idx] = 0
        self.command[idx] = command
        self.phase[idx] = phase
        self.prev_action[idx] = 0.0
        self.prev_target[idx] = nominal
        self.nominal_angle[idx] = nominal

        self._physics_reset(idx, qpos, qvel, nominal)
        sim = self._state(idx)
        self.obs[idx] = self._obs(idx, sim, nominal)

    @staticmethod
    def _euler_to_quat(roll: np.ndarray, pitch: np.ndarray, yaw: np.ndarray) -> np.ndarray:
        """MuJoCo [w, x, y, z] quaternion from ZYX Euler angles."""
        cr, sr = np.cos(roll / 2), np.sin(roll / 2)
        cp, sp = np.cos(pitch / 2), np.sin(pitch / 2)
        cy, sy = np.cos(yaw / 2), np.sin(yaw / 2)
        return np.stack([
            cr * cp * cy + sr * sp * sy,
            sr * cp * cy - cr * sp * sy,
            cr * sp * cy + sr * cp * sy,
            cr * cp * sy - sr * sp * cy,
        ], axis=1)

    # ----- PyTorch interface -----

    def _torch_path(self):
        if self._torch is None:
            import torch
            from tensordict import TensorDict
            self._torch, self._TensorDict = torch, TensorDict
        return self._torch, self._TensorDict

    def _to_torch(self, x: np.ndarray):
        torch, _ = self._torch_path()
        return torch.from_numpy(np.asarray(x))

    def _obs_tensor(self):
        _, TensorDict = self._torch_path()
        return TensorDict({"policy": self._to_torch(self.obs)}, batch_size=[self.num_envs])

    @property
    def obs_layout(self) -> dict[str, slice]:
        return dict(self._obs_layout)

    @property
    def episode_length_buf(self):
        return self._to_torch(self.t.copy())

    @episode_length_buf.setter
    def episode_length_buf(self, value) -> None:
        self.t[:] = value.detach().cpu().numpy().astype(np.int32)

    def reset(self):
        self._reset_indices(np.arange(self.num_envs, dtype=np.int64))
        return self._obs_tensor()

    def step(self, actions):
        """One control step.  actions: (num_envs, 8) in [-1, 1]; returns the usual VecEnv tuple."""
        action = np.asarray(actions.detach().cpu().numpy() if hasattr(actions, "detach") else actions,
                            dtype=np.float64)
        if action.shape != (self.num_envs, self.num_actions):
            raise ValueError(f"actions must have shape {(self.num_envs, self.num_actions)}, got {action.shape}")
        action = np.clip(action, -1.0, 1.0)

        # The nominal controller sees the state at the start of the step.
        sim0 = self._state(np.arange(self.num_envs, dtype=np.int64))
        if self.cfg.gait_hz:
            self.phase = np.mod(self.phase + 2 * math.pi * self.cfg.gait_hz * self.dt, 2 * math.pi)
        nominal = self._nominal_angles(sim0["q"], sim0["qd"], self.phase)
        command = np.clip(nominal + self.cfg.residual_scale * action, self.ctrl_low, self.ctrl_high)
        filtered = self.prev_target + self.cfg.action_filter * (command - self.prev_target)
        target = self.prev_target + np.clip(filtered - self.prev_target, -self.max_step, self.max_step)
        target = np.clip(target, self.ctrl_low, self.ctrl_high).astype(np.float32)

        self._physics_step(target)

        # State after the step: reward, failure, observation.
        self.t += 1
        sim = self._state(np.arange(self.num_envs, dtype=np.int64))
        reward, failed, metrics = self._reward(sim, target, action)
        done = failed | (self.t >= self.max_steps)
        time_out = done & ~failed

        self.prev_action[:] = action.astype(np.float32)
        self.prev_target[:] = target
        self.nominal_angle[:] = nominal
        self.obs[:] = self._obs(np.arange(self.num_envs, dtype=np.int64), sim, nominal)
        final_obs = np.nan_to_num(self.obs, nan=0.0, posinf=0.0, neginf=0.0).copy()

        if done.any():
            done_idx = np.flatnonzero(done)
            self._reset_indices(done_idx)
            # _reset_indices writes self.obs for the reset rows; leave the others untouched.

        log = {"/reward_mean": float(np.mean(reward))}
        for k, v in metrics.items():
            log[f"/{k}"] = float(np.nanmean(v))
        self.extras = {
            "time_outs": self._to_torch(time_out.astype(np.float32)),
            "final_observation": self._to_torch(final_obs),
            "log": log,
        }
        return self._obs_tensor(), self._to_torch(reward.astype(np.float32)), self._to_torch(done.astype(np.float32)), self.extras

    def close(self) -> None:
        self._pool.shutdown(wait=True)


def make_dog_env(num_envs: int, backend: str = "cpu", seed: int = 0, **kwargs):
    """Create the batched dog env.

    ``backend="cpu"`` runs plain C MuJoCo in CPU threads (the reference backend).
    ``backend="mjx"`` runs the same task in MuJoCo MJX on the GPU.
    ``backend="auto"`` picks MJX when JAX sees a GPU, else the C backend.
    """
    if backend not in ("cpu", "auto", "mjx"):
        raise ValueError(f"backend must be 'cpu', 'auto' or 'mjx', got {backend!r}")
    if backend == "auto":
        try:
            import jax

            backend = "mjx" if jax.devices("gpu") else "cpu"
        except Exception:
            backend = "cpu"
    if backend == "mjx":
        from pipeline.dog_mjx_env import make_dog_mjx_env

        return make_dog_mjx_env(num_envs, seed=seed, **kwargs)
    env = DogEnv(num_envs, seed=seed, **kwargs)
    print(f"DogEnv: C MuJoCo on CPU, {env.num_threads} physics threads, {env.num_envs} envs")
    return env


