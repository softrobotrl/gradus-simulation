#!/usr/bin/env python3
"""Build the clean ``Leg-Sim`` assembly used by the MuJoCo export.

The original prototype assembly has its 14 disk stations generated by two
assembly linear patterns and its joints expressed as Cylindrical+Planar
surrogate mates.  onshape-to-robot does not expand patterns and only turns
``dof_*`` mates into joints, so the original exports as a pile of free bodies.

This script creates a fresh assembly containing only the 28 half-disk bodies,
with:

* one mate group per station (merges the two printed halves),
* one BALL mate per interface, named ``dof_00`` ... ``dof_12``.

Usage::

    python -m cad.build_sim_assembly
"""

from __future__ import annotations

import argparse
import math
from collections import OrderedDict

import numpy as np

from cad.export_onshape import Onshape

DEFAULT_DOC = "e8da7c50681f40644f3812fb"
DEFAULT_WS = "71bd24dd8d18a5e53f7ffb25"
DEFAULT_PS = "cd41842204143b0c2cc06855"
DEFAULT_SRC_ASM = "a388868beab8a28867031630"


def _post(c, path, body):
    st, r = c.post(path, body)
    if st != 200:
        raise RuntimeError(f"POST {path} -> {st}: {r}")
    return r


def _part_faces(c, did, wid, ps):
    """Largest +Z planar face and mid-thickness z for each disk part."""
    st, data = c.get(f"/api/v9/partstudios/d/{did}/w/{wid}/e/{ps}/bodydetails")
    if st != 200:
        raise RuntimeError(f"bodydetails failed ({st})")
    out = {}
    for body in data["bodies"]:
        name = (body.get("properties") or {}).get("name", "")
        if name == "PRT-BackBone":
            continue
        cand = []
        zmin, zmax = 1e9, -1e9
        for f in body.get("faces", []):
            box = f.get("box")
            if box:
                zmin = min(zmin, box["minCorner"]["z"])
                zmax = max(zmax, box["maxCorner"]["z"])
            s = f.get("surface", {})
            if s.get("type") == "PLANE":
                n = s.get("normal", {})
                if n.get("z", 0) > 0.99:
                    cand.append((f.get("area", 0), f.get("id")))
        if not cand:
            continue
        cand.sort(reverse=True)
        out[body["id"]] = {"face": cand[0][1], "zc": 0.5 * (zmin + zmax)}
    return out


def _source_rows(c, did, wid, src_asm, parts):
    st, data = c.get(f"/api/v16/assemblies/d/{did}/w/{wid}/e/{src_asm}")
    if st != 200:
        raise RuntimeError(f"source assembly failed ({st})")
    ra = data["rootAssembly"]
    inst = {i["id"]: i for i in ra["instances"]}
    rows = []
    for occ in ra["occurrences"]:
        if len(occ["path"]) != 1:
            continue
        i = inst.get(occ["path"][0])
        if not i or i.get("partId") not in parts:
            continue
        T = np.array(occ["transform"], dtype=float).reshape(4, 4)
        rows.append({
            "name": i.get("name", ""),
            "pid": i.get("partId"),
            "T": occ["transform"],
            "z": T[2, 3],
            "ang": math.degrees(math.atan2(T[1, 0], T[0, 0])),
        })
    return rows


def _temp_cs(c, did, wid, eid, path, pid, face):
    feat = {"feature": {"btType": "BTMMateConnector-66", "featureType": "mateConnector",
            "name": "__temp_cs__", "suppressed": False, "parameters": [
        {"btType": "BTMParameterEnum-145", "parameterId": "originType",
         "enumName": "Origin type", "value": "ON_ENTITY"},
        {"btType": "BTMParameterQueryWithOccurrenceList-67", "parameterId": "originQuery",
         "queries": [{"btType": "BTMInferenceQueryWithOccurrence-1083",
                      "inferenceType": "CENTROID", "path": [path],
                      "deterministicIds": [face]}]}]}}
    res = _post(c, f"/api/v9/assemblies/d/{did}/w/{wid}/e/{eid}/features", feat)
    fid = res["feature"]["featureId"]
    _, data = c.get(f"/api/v16/assemblies/d/{did}/w/{wid}/e/{eid}",
                    "includeMateFeatures=true&includeMateConnectors=true")
    cs = None
    for f in data["rootAssembly"].get("features", []):
        if (f.get("featureId") or f.get("id")) == fid:
            cs = f["featureData"]["mateConnectorCS"]
            break
    c.request("DELETE", f"/api/v9/assemblies/d/{did}/w/{wid}/e/{eid}/features/featureid/{fid}")
    if cs is None:
        raise RuntimeError(f"temp CS missing for {pid}")
    return cs


def _connector(c, did, wid, eid, path, face, p0, Rface, anchor_world, T, name):
    a_local = (np.linalg.inv(T) @ np.array([*anchor_world, 1.0]))[:3]
    off = Rface.T @ (a_local - p0)
    feat = {"feature": {"btType": "BTMMateConnector-66", "featureType": "mateConnector",
            "name": name, "suppressed": False, "parameters": [
        {"btType": "BTMParameterEnum-145", "parameterId": "originType",
         "enumName": "Origin type", "value": "ON_ENTITY"},
        {"btType": "BTMParameterQueryWithOccurrenceList-67", "parameterId": "originQuery",
         "queries": [{"btType": "BTMInferenceQueryWithOccurrence-1083",
                      "inferenceType": "CENTROID", "path": [path],
                      "deterministicIds": [face]}]},
        {"btType": "BTMParameterBoolean-144", "parameterId": "transform", "value": True},
        {"btType": "BTMParameterQuantity-147", "parameterId": "translationX",
         "expression": f"{off[0]} m", "isInteger": False},
        {"btType": "BTMParameterQuantity-147", "parameterId": "translationY",
         "expression": f"{off[1]} m", "isInteger": False},
        {"btType": "BTMParameterQuantity-147", "parameterId": "translationZ",
         "expression": f"{off[2]} m", "isInteger": False},
        {"btType": "BTMParameterEnum-145", "parameterId": "rotationType",
         "enumName": "Rotation axis", "value": "ABOUT_Z"},
        {"btType": "BTMParameterQuantity-147", "parameterId": "rotation",
         "expression": "0 rad", "isInteger": False}]}}
    res = _post(c, f"/api/v9/assemblies/d/{did}/w/{wid}/e/{eid}/features", feat)
    return res["feature"]["featureId"]


def _ball_mate(c, did, wid, eid, name, mc_a, mc_b):
    feat = {"feature": {"btType": "BTMMate-64", "featureType": "mate", "name": name,
            "suppressed": False, "parameters": [
        {"btType": "BTMParameterEnum-145", "parameterId": "mateType",
         "enumName": "Mate type", "value": "BALL"},
        {"btType": "BTMParameterQueryWithOccurrenceList-67",
         "parameterId": "mateConnectorsQuery", "queries": [
            {"btType": "BTMFeatureQueryWithOccurrence-157", "featureId": mc_a,
             "path": [], "queryData": ""},
            {"btType": "BTMFeatureQueryWithOccurrence-157", "featureId": mc_b,
             "path": [], "queryData": ""}]}]}}
    res = _post(c, f"/api/v9/assemblies/d/{did}/w/{wid}/e/{eid}/features", feat)
    return res["feature"]["featureId"]


def _group(c, did, wid, eid, name, path_a, path_b):
    feat = {"feature": {"btType": "BTMMateGroup-65", "featureType": "mateGroup",
            "name": name, "suppressed": False, "parameters": [
        {"btType": "BTMParameterQueryWithOccurrenceList-67",
         "parameterId": "occurrencesQuery", "queries": [
            {"btType": "BTMIndividualOccurrenceQuery-626", "path": [path_a]},
            {"btType": "BTMIndividualOccurrenceQuery-626", "path": [path_b]}]}]}}
    _post(c, f"/api/v9/assemblies/d/{did}/w/{wid}/e/{eid}/features", feat)


def build(did=DEFAULT_DOC, wid=DEFAULT_WS, ps=DEFAULT_PS, src_asm=DEFAULT_SRC_ASM,
          name="Leg-Sim") -> str:
    c = Onshape()
    parts = _part_faces(c, did, wid, ps)
    rows = _source_rows(c, did, wid, src_asm, parts)

    hip = sorted([r for r in rows if r["pid"] == "J4D"], key=lambda r: r["ang"])
    rest = sorted([r for r in rows if r["pid"] != "J4D"], key=lambda r: (r["z"], r["ang"]))
    order = hip + rest

    asm = _post(c, f"/api/v9/assemblies/d/{did}/w/{wid}", {"name": name})
    eid = asm["id"]

    groups = [{"transform": r["T"], "instances": [{
        "documentId": did, "elementId": ps, "partId": r["pid"], "isAssembly": False}]}
        for r in order]
    res = _post(c, f"/api/v16/assemblies/d/{did}/w/{wid}/e/{eid}/transformedinstances",
                {"transformGroups": groups})
    for r, ins in zip(order, res["insertInstanceResponses"]):
        r["path"] = ins["occurrences"][0]["path"][0]

    stations: "OrderedDict[tuple, list]" = OrderedDict()
    for r in order:
        stations.setdefault((r["pid"], round(r["z"], 4)), []).append(r)
    st_list = sorted(stations.items(), key=lambda kv: -kv[0][1])

    for k, (_, rs) in enumerate(st_list):
        if len(rs) == 2:
            _group(c, did, wid, eid, f"merge_{k:02d}", rs[0]["path"], rs[1]["path"])

    cs = {}
    for pid, info in parts.items():
        r = next(x for x in order if x["pid"] == pid)
        raw = _temp_cs(c, did, wid, eid, r["path"], pid, info["face"])
        cs[pid] = (np.array(raw["origin"], dtype=float),
                   np.column_stack([raw["xAxis"], raw["yAxis"], raw["zAxis"]]))

    centers = []
    for (pid, z), rs in st_list:
        centers.append((pid, z + parts[pid]["zc"], rs[0]))

    for j in range(len(centers) - 1):
        anchor = np.array([0.0, 0.0, 0.5 * (centers[j][1] + centers[j + 1][1])])
        ids = []
        for k in (j, j + 1):
            pid, _, r = centers[k]
            p0, Rf = cs[pid]
            T = np.array(r["T"], dtype=float).reshape(4, 4)
            ids.append(_connector(c, did, wid, eid, r["path"], parts[pid]["face"],
                                  p0, Rf, anchor, T, f"joint_{j:02d}_{'ab'[k-j]}"))
        _ball_mate(c, did, wid, eid, f"dof_{j:02d}", ids[0], ids[1])

    print(f"* built {name}: {eid} ({len(order)} instances, {len(centers)-1} ball mates)")
    return eid


def is_valid(did: str, wid: str, eid: str) -> bool:
    """True if the assembly is the clean 28-instance / 13-ball-DOF Leg-Sim."""
    c = Onshape()
    try:
        st, data = c.get(f"/api/v16/assemblies/d/{did}/w/{wid}/e/{eid}",
                         "includeMateFeatures=true")
    except Exception:
        return False
    if st != 200:
        return False
    ra = data.get("rootAssembly", {})
    if len(ra.get("instances", [])) != 28:
        return False
    dofs = [f for f in ra.get("features", [])
            if f.get("featureType") == "mate"
            and f.get("featureData", {}).get("name", "").startswith("dof_")]
    return len(dofs) == 13 and all(
        f["featureData"].get("mateType") == "BALL" for f in dofs)


def ensure(did=DEFAULT_DOC, wid=DEFAULT_WS, ps=DEFAULT_PS,
           src_asm=DEFAULT_SRC_ASM, name="Leg-Sim") -> str:
    """Reuse a valid Leg-Sim, otherwise build a new one."""
    c = Onshape()
    st, els = c.get(f"/api/v6/documents/d/{did}/w/{wid}/elements")
    if st == 200:
        for e in els:
            if e.get("elementType") != "ASSEMBLY" or e.get("name") != name:
                continue
            eid = e.get("id")
            if is_valid(did, wid, eid):
                print(f"* reusing {name}: {eid}")
                return eid
    return build(did, wid, ps, src_asm, name)


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--document", default=DEFAULT_DOC)
    p.add_argument("--workspace", default=DEFAULT_WS)
    p.add_argument("--partstudio", default=DEFAULT_PS)
    p.add_argument("--source-assembly", default=DEFAULT_SRC_ASM)
    p.add_argument("--name", default="Leg-Sim")
    args = p.parse_args()
    print(build(args.document, args.workspace, args.partstudio,
                args.source_assembly, args.name))


if __name__ == "__main__":
    main()
